#!/usr/bin/env python3
"""Regenerate checked-in SPIR-V from FrostBox's own MIT shader sources."""
import pathlib,struct,subprocess,tempfile
root=pathlib.Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as tmp:
    result=['// SPDX-License-Identifier: MIT','// Generated by scripts/build-vulkan-shaders.py; Vulkan 1.0 target.','#pragma once','#include <cstdint>']
    for stage in ('vert','frag'):
        dest=pathlib.Path(tmp)/stage
        subprocess.run(['glslangValidator','-V','--target-env','vulkan1.0',str(root/f'graphics/vulkan/shaders/triangle.{stage}'),'-o',str(dest)],check=True)
        words=struct.unpack('<'+'I'*(dest.stat().st_size//4),dest.read_bytes())
        result.append(f'inline constexpr uint32_t triangle_{stage}[]={{')
        for i in range(0,len(words),8):result.append(','.join(hex(x) for x in words[i:i+8])+',')
        result.append('};')
    (root/'graphics/vulkan/shaders.hpp').write_text('\n'.join(result)+'\n')
